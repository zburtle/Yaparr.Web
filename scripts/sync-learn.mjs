// Turns the guides of the Yaparr repository (docs/guides/*.md) into src/app/learn-content.ts, which the /learn pages show.
// The Markdown there is the source: change it in the Yaparr repository, then run this here and commit the result.
//
//   node scripts/sync-learn.mjs ../Yaparr/docs/guides
//
// Only what the guides use is understood: a # title, ## sections, paragraphs, - lists, and **bold**, *italic*, `code` and [links](...) inside them.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DOCS = 'https://github.com/zburtle/Yaparr/blob/master/docs/';

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: node scripts/sync-learn.mjs <path to docs/guides in the Yaparr repository>');
  process.exit(1);
}

// How GitHub makes an anchor of a heading, so a link to #heading from the apps lands on the same place.
const anchor = heading => heading.trim().toLowerCase().replace(/[^\p{L}\p{N} -]/gu, '').replace(/ /g, '-');

function link(text, href, file) {
  if (/^https:\/\//.test(href)) return { k: 'link', t: text, href };
  const m = /^(\.\.\/)?([A-Za-z0-9-]+)\.md(?:#([a-z0-9-]+))?$/.exec(href);
  if (!m) throw new Error(`${file}: a link this script does not know: ${href}`);
  if (m[1]) return { k: 'link', t: text, href: DOCS + m[2] + '.md' + (m[3] ? '#' + m[3] : '') };
  return m[2] === 'README' ? { k: 'link', t: text, to: '/learn' } : { k: 'link', t: text, to: '/learn/' + m[2], ...(m[3] ? { fragment: m[3] } : {}) };
}

function inline(text, file) {
  const out = [];
  const re = /\[([^\]]+)\]\(([^)]+)\)|\*\*(.+?)\*\*|\*(.+?)\*|`([^`]+)`/g;
  let last = 0;
  for (let m; (m = re.exec(text)); last = re.lastIndex) {
    if (m.index > last) out.push({ k: 'text', t: text.slice(last, m.index) });
    if (m[1] !== undefined) out.push(link(m[1], m[2], file));
    else if (m[3] !== undefined) out.push({ k: 'strong', t: m[3] });
    else if (m[4] !== undefined) out.push({ k: 'em', t: m[4] });
    else out.push({ k: 'code', t: m[5] });
  }
  if (last < text.length) out.push({ k: 'text', t: text.slice(last) });
  return out;
}

function parse(file) {
  const page = { title: '', sections: [{ blocks: [] }] };
  let section = page.sections[0];
  let paragraph = [];
  let list = null;
  const endParagraph = () => {
    if (paragraph.length) section.blocks.push({ k: 'p', i: inline(paragraph.join(' '), file) });
    paragraph = [];
  };
  const endList = () => {
    if (list) section.blocks.push({ k: 'ul', items: list });
    list = null;
  };
  for (const line of readFileSync(join(dir, file), 'utf8').split(/\r?\n/)) {
    if (/^# /.test(line)) { endParagraph(); endList(); page.title = line.slice(2).trim(); }
    else if (/^## /.test(line)) {
      endParagraph(); endList();
      const heading = line.slice(3).trim();
      section = { id: anchor(heading), heading, blocks: [] };
      page.sections.push(section);
    } else if (/^- /.test(line)) { endParagraph(); (list ??= []).push(inline(line.slice(2).trim(), file)); }
    else if (line.trim() === '') { endParagraph(); endList(); }
    else if (/^\s/.test(line) && list) list[list.length - 1].push(...inline(' ' + line.trim(), file));
    else { endList(); paragraph.push(line.trim()); }
  }
  endParagraph(); endList();
  page.sections = page.sections.filter(s => s.heading || s.blocks.length);
  return page;
}

const files = readdirSync(dir).filter(f => f.endsWith('.md')).sort();
const index = parse('README.md');
const pages = files.filter(f => f !== 'README.md').map(f => ({ slug: f.replace(/\.md$/, ''), ...parse(f) }));
if (pages.some(p => !p.title)) throw new Error('A guide has no # title.');

// The index lists the guides in its own order.
const listed = index.sections.flatMap(s => s.blocks).find(b => b.k === 'ul')?.items ?? [];
const order = listed.map(item => item.find(p => p.k === 'link')?.to?.slice('/learn/'.length)).filter(Boolean);
const missing = pages.filter(p => !order.includes(p.slug)).map(p => p.slug);
if (missing.length) throw new Error('Not in the index: ' + missing.join(', '));

const content = {
  title: index.title,
  intro: index.sections.flatMap(s => s.blocks).filter(b => b.k === 'p').map(b => b.i),
  pages: order.map(slug => pages.find(p => p.slug === slug)),
  listed,
};

writeFileSync(
  new URL('../src/app/learn-content.ts', import.meta.url),
  `// Generated by scripts/sync-learn.mjs from docs/guides in the Yaparr repository. Do not edit: change the guides there and run the script again.\n` +
    `import type { Content } from './learn-types';\n\nexport const CONTENT: Content = ${JSON.stringify(content, null, 2)};\n`,
);
console.log(`${pages.length} guides written to src/app/learn-content.ts`);
